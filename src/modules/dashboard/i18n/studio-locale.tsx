const dictionaries = { en: english, "zh-CN": chinese };

type StudioLocaleContextValue = {
  locale: StudioLocale;
  copy: (typeof dictionaries)[StudioLocale];
  setLocale: (locale: StudioLocale) => void;
};

const StudioLocaleContext = createContext<StudioLocaleContextValue | null>(null);

const isStudioLocale = (value: string | null): value is StudioLocale =>
  value === "en" || value === "zh-CN";

export const StudioLocaleProvider = ({ children }: { children: ReactNode }) => {
  const [locale, setLocaleState] = useState<StudioLocale>("en");

  useEffect(() => {
    const savedLocale = window.localStorage.getItem(STORAGE_KEY);
    const preferredLocale = navigator.language.toLowerCase().startsWith("zh")
      ? "zh-CN"
      : "en";
    setLocaleState(isStudioLocale(savedLocale) ? savedLocale : preferredLocale);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = (nextLocale: StudioLocale) => {
    window.localStorage.setItem(STORAGE_KEY, nextLocale);
    startTransition(() => setLocaleState(nextLocale));
  };

  const value = useMemo(
    () => ({ locale, copy: dictionaries[locale], setLocale }),
    [locale],
  );

  return (
    <StudioLocaleContext.Provider value={value}>
      {children}
    </StudioLocaleContext.Provider>
  );
};

export const useStudioLocale = () => {
  const context = useContext(StudioLocaleContext);
  if (!context) {
    throw new Error("useStudioLocale must be used inside StudioLocaleProvider");
  }
  return context;
};
